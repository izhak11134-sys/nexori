import { writeFile } from 'node:fs/promises';
import { contentGroups, contentFields } from '../src/content.js';
import { schemaChunks } from '../src/spark-content.js';

const quote=JSON.stringify;
if(schemaChunks.length>8)throw new Error('The expanded schema exceeds Firestore rule access limits. Redesign and test validation before publishing rules.');
const functions=Object.entries(contentGroups).map(([group,{records}])=>{
  const fields=contentFields[group],publicFields=fields.filter(field=>!['editorNotes','retailerUrl'].includes(field));
  const images=fields.filter(field=>/image$/i.test(field));
  return `    function patch_${group}(p, published, pattern) {
      return p is map && p.keys().hasOnly(${group==='products'?`published ? ${quote(publicFields)} : ${quote(fields)}`:quote(fields)})${images.map(field=>`\n        && p.get(${quote(field)}, '').matches(pattern)`).join('')};
    }`;
}).join('\n');
const chunkFunctions=schemaChunks.map(chunk=>`    function chunk_${chunk.id.replace('-','_')}(r, published, pattern) {
      return r is map && r.keys().hasOnly(${quote(contentGroups[chunk.group].records.map(record=>record.id))})${chunk.ids.map(id=>`\n        && (!(${quote(id)} in r) || patch_${chunk.group}(r[${quote(id)}], published, pattern))`).join('')};
    }`).join('\n');
const groups=Object.keys(contentGroups);
const rules=`// Generated by scripts/build-firestore-rules.mjs from the approved card schema.
// Auth + Firestore only. No Functions, Storage or billing activation.
rules_version = '2';
service cloud.firestore {
  match /databases/{database}/documents {
    function owner() {
      return request.auth != null && request.auth.token.email_verified == true
        && get(/databases/$(database)/documents/admins/$(request.auth.uid)).data.active == true;
    }
    function uuid(id) { return id is string && id.matches('[a-f0-9-]{36}'); }
${functions}
${chunkFunctions}
    function payloadHeader(p) {
      return p is map && p.keys().hasOnly(['version', 'changes']) && p.version == 1
        && p.changes is map && p.changes.keys().hasOnly(${quote(groups)});
    }
    function groupData(group, records, published) {
      let pattern = published ? '(|spark:published/[a-f0-9-]{36}/[a-f0-9-]{36})'
        : '(|spark:published/[a-f0-9-]{36}/[a-f0-9-]{36}|spark:drafts/' + request.auth.uid + '/[a-f0-9-]{36})';
      return ${schemaChunks.map(chunk=>`(group == ${quote(chunk.id)} && chunk_${chunk.id.replace('-','_')}(records, published, pattern))`).join('\n        || ')};
    }
    function draftEnvelope() {
      let d = request.resource.data;
      return d.keys().hasOnly(['payload', 'revision', 'draftId', 'updatedAt', 'updatedBy'])
        && d.revision is int && d.updatedBy == request.auth.uid && d.updatedAt == request.time
        && uuid(d.draftId) && payloadHeader(d.payload)${schemaChunks.map(chunk=>`\n        && get(/databases/$(database)/documents/draftContent/$(request.auth.uid)/versions/$(d.draftId)/groups/${chunk.id}).data.records == d.payload.changes.get(${quote(chunk.group)}, {})`).join('')};
    }
    function publicEnvelope() {
      let d = request.resource.data;
      let release = getAfter(/databases/$(database)/documents/mediaReleases/$(d.revisionId)).data;
      return d.keys().hasOnly(['payload', 'revision', 'revisionId', 'updatedAt'])
        && d.revision is int && uuid(d.revisionId) && d.updatedAt == request.time
        && payloadHeader(d.payload) && release.revision == d.revision${schemaChunks.map(chunk=>`\n        && get(/databases/$(database)/documents/publishedContent/$(d.revisionId)/groups/${chunk.id}).data.records == d.payload.changes.get(${quote(chunk.group)}, {})`).join('')};
    }
    function imageData() {
      let d = request.resource.data;
      return d.bytes is bytes && d.bytes.size() > 0 && d.bytes.size() <= 196608
        && d.mime == 'image/webp' && d.createdAt == request.time;
    }
    match /admins/{uid} {
      allow get: if request.auth != null && request.auth.uid == uid;
      allow list, write: if false;
    }
    match /cms/draft {
      allow read: if owner();
      allow create: if owner() && draftEnvelope() && request.resource.data.revision == 1;
      allow update: if owner() && draftEnvelope() && request.resource.data.revision == resource.data.revision + 1;
      allow delete: if false;
    }
    match /draftContent/{uid}/versions/{version}/groups/{group} {
      allow read: if owner() && request.auth.uid == uid;
      allow create: if owner() && request.auth.uid == uid && uuid(version)
        && request.resource.data.keys().hasOnly(['records', 'createdAt'])
        && request.resource.data.createdAt == request.time
        && groupData(group, request.resource.data.records, false);
      allow update, delete: if false;
    }
    match /publishedContent/{release}/groups/{group} {
      allow read: if exists(/databases/$(database)/documents/mediaReleases/$(release));
      allow create: if owner() && uuid(release)
        && request.resource.data.keys().hasOnly(['records', 'createdAt'])
        && request.resource.data.createdAt == request.time
        && groupData(group, request.resource.data.records, true)
        && !exists(/databases/$(database)/documents/mediaReleases/$(release));
      allow update, delete: if false;
    }
    match /public/site {
      allow read: if true;
      allow create: if owner() && publicEnvelope() && request.resource.data.revision == 1;
      allow update: if owner() && publicEnvelope() && request.resource.data.revision == resource.data.revision + 1;
      allow delete: if false;
    }
    match /revisions/{id} {
      allow read: if owner();
      allow create: if owner()
        && request.resource.data.keys().hasOnly(['payload', 'revision', 'createdAt', 'kind'])
        && request.resource.data.createdAt == request.time
        && ((id == 'initial' && !exists(/databases/$(database)/documents/public/site)
          && getAfter(/databases/$(database)/documents/public/site).data.revision == 1
          && request.resource.data.revision == 0 && request.resource.data.kind == 'initial'
          && request.resource.data.payload == {'version': 1, 'changes': {}})
        || (uuid(id) && request.resource.data.kind in ['publish', 'restore']
          && getAfter(/databases/$(database)/documents/public/site).data.revisionId == id
          && getAfter(/databases/$(database)/documents/public/site).data.revision == request.resource.data.revision
          && getAfter(/databases/$(database)/documents/public/site).data.payload == request.resource.data.payload));
      allow update, delete: if false;
    }
    match /mediaReleases/{id} {
      allow read: if owner();
      allow create: if owner() && uuid(id)
        && request.resource.data.keys().hasOnly(['revision', 'createdAt'])
        && request.resource.data.createdAt == request.time
        && getAfter(/databases/$(database)/documents/public/site).data.revisionId == id
        && getAfter(/databases/$(database)/documents/public/site).data.revision == request.resource.data.revision
        && getAfter(/databases/$(database)/documents/revisions/$(id)).data.revision == request.resource.data.revision
        && getAfter(/databases/$(database)/documents/revisions/$(id)).data.payload == getAfter(/databases/$(database)/documents/public/site).data.payload;
      allow update, delete: if false;
    }
    match /draftImages/{uid}/images/{id} {
      allow read: if owner() && request.auth.uid == uid;
      allow create: if owner() && request.auth.uid == uid && uuid(id) && imageData()
        && request.resource.data.keys().hasOnly(['bytes', 'mime', 'createdAt']);
      allow update, delete: if false;
    }
    match /publishedImages/{release}/images/{id} {
      allow read: if exists(/databases/$(database)/documents/mediaReleases/$(release));
      allow create: if owner() && uuid(release) && uuid(id) && imageData()
        && request.resource.data.keys().hasOnly(['bytes', 'mime', 'sourceId', 'createdAt'])
        && uuid(request.resource.data.sourceId)
        && !exists(/databases/$(database)/documents/mediaReleases/$(release))
        && request.resource.data.bytes == get(/databases/$(database)/documents/draftImages/$(request.auth.uid)/images/$(request.resource.data.sourceId)).data.bytes;
      allow update, delete: if false;
    }
    match /{document=**} { allow read, write: if false; }
  }
}
`;
await writeFile(new URL('../firestore.rules',import.meta.url),rules);
console.log('Generated Spark-only Firestore rules for the approved cards.');
